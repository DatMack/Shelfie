const farewellIndexKey = 'shelfie-farewell-index-v1'

export function nextBookFarewell() {
  let index = 0
  try {
    index = Math.max(0, Number.parseInt(localStorage.getItem(farewellIndexKey) ?? '0', 10) || 0)
    localStorage.setItem(farewellIndexKey, String(index + 1))
  } catch {
    // Private browsing can block storage; the first farewell still works.
  }
  return bookFarewells[index % bookFarewells.length]
}
